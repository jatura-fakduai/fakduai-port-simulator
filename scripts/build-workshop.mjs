import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const escape=s=>s.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
const template=read('docs/codelab/codelab-template.html');
const workflow=read('n8n/Fakduai-Freight-Full-Release.json');
JSON.parse(workflow);
const starter=JSON.stringify(JSON.parse(workflow)).replaceAll('</','<\\/');
for(const token of ['{{SYSTEM_PROMPT}}','{{STARTER_WF}}'])if(template.split(token).length!==2)throw new Error('Codelab template must contain '+token+' exactly once');
const body=template.replace('{{SYSTEM_PROMPT}}',()=>escape(read('n8n/Freight-System-Prompt.txt').trim())).replace('{{STARTER_WF}}',()=>starter);
const html='<!doctype html>\n<html lang="th">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n<link rel="icon" href="img/mark-fakduai.png">\n</head>\n<body>\n'+body+'\n</body>\n</html>\n';
fs.mkdirSync(path.join(root,'public/codelab'),{recursive:true});
fs.writeFileSync(path.join(root,'public/codelab/index.html'),html);
fs.mkdirSync(path.join(root,'public/downloads'),{recursive:true});
fs.copyFileSync(path.join(root,'docs/Google-Sheet-Template.xlsx'),path.join(root,'public/downloads/Google-Sheet-Template.xlsx'));
for(const [src,dest] of [['n8n/Fakduai-Freight-Full-Release.json','Fakduai-Port-LINE.json'],['n8n/Freight-System-Prompt.txt','Freight-System-Prompt.txt'],['google-apps-script/Code.gs','Code.gs'],...['SETUP','DATA-SCHEMA','TEST-PROMPTS','DEPLOY'].map(n=>['docs/'+n+'.md',n+'.md'])])fs.copyFileSync(path.join(root,src),path.join(root,'public/downloads',dest));
console.log('Built LINE codelab and downloads');
